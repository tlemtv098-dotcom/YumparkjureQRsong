def register_thai_fonts():
    """Register a TrueType font pair that covers Thai with reportlab.

    reportlab's built-in Type-1 fonts have no Thai glyphs at all, so Thai text
    comes out as black boxes (or raises) unless a real TTF is registered.
    Returns (regular_name, bold_name) or exits with a clear message.
    """
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    windows_fonts = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
    candidates = [
        ("LeelawUI.ttf", "LeelaUIb.ttf", "Leelawadee UI"),
        ("leelawad.ttf", "leelawdb.ttf", "Leelawadee"),
        ("tahoma.ttf", "tahomabd.ttf", "Tahoma"),
    ]
    thai_range = range(0x0E01, 0x0E5B)

    for regular_file, bold_file, family in candidates:
        regular_path = os.path.join(windows_fonts, regular_file)
        bold_path = os.path.join(windows_fonts, bold_file)
        if not (os.path.isfile(regular_path) and os.path.isfile(bold_path)):
            continue
        try:
            probe = TTFont("probe", regular_path)
            covered = len(set(thai_range) & set(probe.face.charToGlyph))
        except Exception:
            continue
        if covered < 50:
            continue
        pdfmetrics.registerFont(TTFont("Thai", regular_path))
        pdfmetrics.registerFont(TTFont("Thai-Bold", bold_path))
        pdfmetrics.registerFontFamily(
            "Thai", normal="Thai", bold="Thai-Bold", italic="Thai", boldItalic="Thai-Bold"
        )
        return "Thai", "Thai-Bold", family, covered

    sys.stderr.write(
        "ERROR: no Thai-capable TrueType font found. Looked for "
        "LeelawUI.ttf, leelawad.ttf and tahoma.ttf in %s\n"
        "Install the Leelawadee UI or Tahoma font, then run this script again.\n"
        % windows_fonts
    )
    raise SystemExit(2)


