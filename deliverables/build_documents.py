def _block_text(blk):
    """Every scrap of text a block will render, for the font-coverage check."""
    if "text" in blk:
        return [blk["text"]]
    out = []
    for key in ("items", "bullets", "rows"):
        value = blk.get(key)
        if not value:
            continue
        if key == "rows":
            for row in value:
                out.extend(str(c) for c in row)
        else:
            out.extend(str(v) for v in value)
    if "head" in blk:
        out.extend(str(h) for h in blk["head"])
    return out


def check_font_coverage(blocks, font_name):
    """Fail loudly on any character the registered font cannot draw.

    A missing glyph does not raise in reportlab: it is emitted as .notdef and
    prints as a black box. Thai documents are full of arrows and dashes, and
    Leelawadee UI has no arrow glyphs at all, so this is checked rather than
    discovered by reading the PDF.
    """
    from reportlab.pdfbase import pdfmetrics

    covered = set(pdfmetrics.getFont(font_name).face.charToGlyph)
    missing = {}
    for blk in blocks:
        for text in _block_text(blk):
            for ch in text:
                if ch in ("\n", "\r", "\t"):
                    continue
                if ord(ch) not in covered:
                    missing.setdefault(ch, 0)
                    missing[ch] += 1
    if missing:
        listed = ", ".join("U+%04X x%d" % (ord(c), n) for c, n in sorted(missing.items()))
        raise SystemExit(
            "ERROR: the registered font cannot draw these characters: %s\n"
            "Replace them with plain ASCII equivalents and run again." % listed
        )


