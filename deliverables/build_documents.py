def _set_run_font(run, name, size=None, bold=None, colour=None):
    from docx.shared import Pt, RGBColor

    run.font.name = name
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if colour is not None:
        run.font.color.rgb = RGBColor(*colour)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(
        "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}rFonts"
    )
    if rfonts is None:
        from docx.oxml.ns import qn

        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}" + attr.split(":")[1],
            name,
        )


def render_docx(blocks, out_path, family, title, subtitle):
    import docx
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Cm, Pt, RGBColor

    document = docx.Document()
    normal = document.styles["Normal"]
    normal.font.name = family
    normal.font.size = Pt(11)
    rpr = normal.element.get_or_add_rPr()
    from docx.oxml.ns import qn

    rfonts = rpr.get_or_add_rFonts()
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), family)

    for style_name, size in (("Heading 1", 17), ("Heading 2", 13.5), ("Heading 3", 12)):
        st = document.styles[style_name]
        st.font.name = family
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = RGBColor(0x0F, 0x17, 0x2A)
        r = st.element.get_or_add_rPr()
        rf = r.get_or_add_rFonts()
        for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rf.set(qn(attr), family)

    section = document.sections[0]
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(2.0)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    def para(text, size=11, bold=False, align=None, colour=None, space_after=6):
        p = document.add_paragraph()
        if align is not None:
            p.alignment = align
        p.paragraph_format.space_after = Pt(space_after)
        run = p.add_run(text)
        _set_run_font(run, family, size, bold, colour)
        return p

    para(title, 26, True, WD_ALIGN_PARAGRAPH.CENTER, (0x0F, 0x17, 0x2A), 10)
    para(subtitle, 14, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69), 6)
    para("ทดสอบใช้งานได้ที่ " + LIVE_URL, 11, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69))
    para("ที่เก็บซอร์สโค้ด " + GITHUB_URL, 11, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69))
    para("กำหนดส่ง " + SUBMIT_DATE, 11, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69), 12)
    for _line in STUDENT_LINES:
        para(_line, 12, True, WD_ALIGN_PARAGRAPH.CENTER, (0x0F, 0x17, 0x2A))
    document.add_page_break()

    for blk in blocks:
        kind = blk["t"]
        if kind == "h1":
            h = document.add_heading(level=1)
            _set_run_font(h.add_run(blk["text"]), family, 17, True, (0x0F, 0x17, 0x2A))
        elif kind == "h2":
            h = document.add_heading(level=2)
            _set_run_font(h.add_run(blk["text"]), family, 13.5, True, (0x1D, 0x4E, 0xD8))
        elif kind == "p":
            para(blk["text"])
        elif kind == "center":
            para(blk["text"], 12, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69), 4)
        elif kind == "ul":
            for item in blk["items"]:
                para("•  " + item, 11, False, None, None, 3)
        elif kind == "ol":
            for n, item in enumerate(blk["items"], 1):
                para("%d.  %s" % (n, item), 11, False, None, None, 3)
        elif kind == "code":
            for ln in blk["text"].split("\n"):
                p = document.add_paragraph()
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.left_indent = Cm(0.5)
                _set_run_font(p.add_run(ln if ln else " "), "Consolas", 9.5, False, (0x0F, 0x17, 0x2A))
            document.add_paragraph().paragraph_format.space_after = Pt(6)
        elif kind == "note":
            p = document.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.3)
            _set_run_font(p.add_run("หมายเหตุ: "), family, 10.5, True, (0x78, 0x35, 0x0F))
            _set_run_font(p.add_run(blk["text"]), family, 10.5, False, (0x78, 0x35, 0x0F))
        elif kind == "table":
            table = document.add_table(rows=1, cols=len(blk["head"]))
            table.style = "Table Grid"
            table.alignment = WD_TABLE_ALIGNMENT.LEFT
            hdr = table.rows[0].cells
            for i, text in enumerate(blk["head"]):
                hdr[i].text = ""
                _set_run_font(hdr[i].paragraphs[0].add_run(text), family, 9.5, True)
            for row in blk["rows"]:
                cells = table.add_row().cells
                for i, value in enumerate(row):
                    cells[i].text = ""
                    _set_run_font(cells[i].paragraphs[0].add_run(str(value)), family, 9.5)
            document.add_paragraph().paragraph_format.space_after = Pt(6)
        elif kind == "img":
            path = _resolve_image(blk["file"])
            if not path:
                raise SystemExit("missing image: %s" % blk["file"])
            p = document.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.add_run().add_picture(path, width=Cm(min(blk.get("w", 470) / 28.35, 16.5)))
            para(blk["cap"], 9.5, False, WD_ALIGN_PARAGRAPH.CENTER, (0x47, 0x55, 0x69), 12)
        elif kind == "pagebreak":
            document.add_page_break()
        else:
            raise SystemExit("unknown block type: %s" % kind)

    document.save(out_path)
    return out_path


