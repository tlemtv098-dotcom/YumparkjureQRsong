def render_pptx(slides, out_path, family):
    from pptx import Presentation
    from pptx.dml.color import RGBColor
    from pptx.enum.text import PP_ALIGN
    from pptx.util import Emu, Pt

    prs = Presentation()
    prs.slide_width = Emu(12192000)
    prs.slide_height = Emu(6858000)
    blank = prs.slide_layouts[6]

    AMBER = RGBColor(0xD9, 0x77, 0x06)
    DARK = RGBColor(0x0F, 0x17, 0x2A)
    GREY = RGBColor(0x47, 0x55, 0x69)

    def textbox(slide, x, y, w, h):
        box = slide.shapes.add_textbox(Emu(x), Emu(y), Emu(w), Emu(h))
        box.text_frame.word_wrap = True
        return box.text_frame

    def style(run, size, bold, colour):
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = colour
        run.font.name = family
        from pptx.oxml.ns import qn

        rpr = run._r.get_or_add_rPr()
        for tag in ("a:latin", "a:cs", "a:ea"):
            el = rpr.find(qn(tag))
            if el is None:
                el = rpr.makeelement(qn(tag), {})
                rpr.append(el)
            el.set("typeface", family)

    for spec in slides:
        slide = prs.slides.add_slide(blank)
        kind = spec.get("kind", "bullets")

        if kind == "title":
            tf = textbox(slide, 800000, 2100000, 10592000, 1800000)
            lines = spec["title"].split("\n")
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.CENTER
            r = p.add_run()
            r.text = lines[0]
            style(r, 40, True, DARK)
            if len(lines) > 1:
                p2 = tf.add_paragraph()
                p2.alignment = PP_ALIGN.CENTER
                r2 = p2.add_run()
                r2.text = lines[1]
                style(r2, 18, False, GREY)
            tf2 = textbox(slide, 800000, 4300000, 10592000, 1200000)
            for i, line in enumerate(spec["sub"].split("\n")):
                p = tf2.paragraphs[0] if i == 0 else tf2.add_paragraph()
                p.alignment = PP_ALIGN.CENTER
                r = p.add_run()
                r.text = line
                style(r, 15, False, AMBER if i == 0 else GREY)
            continue

        bar = slide.shapes.add_shape(1, Emu(0), Emu(0), Emu(12192000), Emu(150000))
        bar.fill.solid()
        bar.fill.fore_color.rgb = AMBER
        bar.line.fill.background()
        bar.shadow.inherit = False

        tf = textbox(slide, 640000, 420000, 10912000, 900000)
        p = tf.paragraphs[0]
        r = p.add_run()
        r.text = spec["title"]
        style(r, 30, True, DARK)

        if kind == "bullets":
            tf = textbox(slide, 780000, 1500000, 10600000, 4200000)
            for i, item in enumerate(spec.get("bullets", [])):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                p.space_after = Pt(14)
                r = p.add_run()
                r.text = "•  " + item
                style(r, 18, False, RGBColor(0x1E, 0x29, 0x3B))
            if spec.get("note"):
                tfn = textbox(slide, 780000, 5750000, 10600000, 700000)
                pn = tfn.paragraphs[0]
                rn = pn.add_run()
                rn.text = spec["note"]
                style(rn, 14, True, AMBER)

        elif kind == "closing":
            tf = textbox(slide, 780000, 1500000, 10600000, 4200000)
            for i, item in enumerate(spec.get("bullets", [])):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                p.space_after = Pt(18)
                r = p.add_run()
                r.text = item
                style(r, 18, i == 0, DARK if i == 0 else RGBColor(0x1E, 0x29, 0x3B))
            tfn = textbox(slide, 780000, 5750000, 10600000, 700000)
            rn = tfn.paragraphs[0].add_run()
            rn.text = "ขอบคุณครับ / ขอบคุณค่ะ"
            style(rn, 20, True, AMBER)

        elif kind == "image":
            path = _resolve_image(spec["file"])
            if not path:
                raise SystemExit("missing slide image: %s" % spec["file"])
            from PIL import Image as PILImage

            iw, ih = PILImage.open(path).size
            max_w, max_h = 10_600_000, 4_300_000
            scale = min(max_w / float(iw), max_h / float(ih))
            w, h = int(iw * scale), int(ih * scale)
            left = int((12192000 - w) / 2)
            slide.shapes.add_picture(path, Emu(left), Emu(1350000), Emu(w), Emu(h))
            if spec.get("note"):
                tfn = textbox(slide, 780000, 5900000, 10600000, 600000)
                rn = tfn.paragraphs[0].add_run()
                rn.text = spec["note"]
                style(rn, 13, True, GREY)

    prs.save(out_path)
    return out_path, len(prs.slides._sldIdLst)


